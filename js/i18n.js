let current = 'ja';
export function setLang(l) { if (STRINGS[l]) current = l; return current; }
export function getLang() { return current; }
export function detectLang(navLang) {
  const l = (navLang || 'ja').toLowerCase();
  if (l.startsWith('ja')) return 'ja';
  if (l.startsWith('zh')) return 'zh';
  if (l.startsWith('ko')) return 'ko';
  if (l.startsWith('en')) return 'en';
  return 'en';
}
export function t(key, params = {}) {
  const s = STRINGS[current][key] ?? STRINGS.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (params[k] ?? `{${k}}`));
}
